export type StoryAccessState = 'available' | 'overview_only' | 'locked';

export function getStoryAccessState(story: { id: string; isUnlocked?: boolean; status?: string }): StoryAccessState {
  if (story.isUnlocked === false || story.status === 'locked') {
    return 'locked';
  }
  if (loadedStories[story.id]) {
    return 'available';
  }
  return 'overview_only';
}

export function getStoryAccessLabel(state: StoryAccessState): string {
  switch (state) {
    case 'available':
      return '열람 가능';
    case 'overview_only':
      return '열람 가능(미수록)';
    case 'locked':
      return '잠김';
  }
}

